import numpy as np
import plotly.graph_objects as go
import streamlit as st

from components.callouts import common_mistake, definition, practical_note, research_note, takeaway
from components.comparison import compare_table
from components.lesson_layout import h2, lesson_footer, lesson_header
from components.quiz import Q, quiz
from core.models import Lesson

LESSON = Lesson(
    id="foundations.architecture.depth_width_dense",
    title_ar="العمق والعرض: الشبكة العميقة والطبقة الكثيفة",
    title_en="Depth & Width: Deep Networks and Dense Layers",
    module="foundations.architecture",
    order=2,
    prerequisites=["foundations.architecture.layers"],
    objectives_ar=["تعريف العمق (عدد الطبقات) والعرض (عدد الوحدات في الطبقة) وأثرهما على القدرة والحساب.", "معرفة قواعد عملية أولية لاختيارهما للجداول.", "فهم لماذا العمق يفيد أكثر من العرض في كثير من الحالات (تركيب الخصائص)."],
    terms=["hyperparameter"],
    labs=["labs.network_builder"],
    difficulty="beginner",
    summary_ar="العمق = عدد الطبقات، العرض = وحدات كل طبقة؛ كلاهما معلمات فائقة تحدد القدرة؛ ابدأ صغيرًا ووسّع عند قصور التعلم.",
)


def render() -> None:
    lesson_header(LESSON)
    h2("تعريفات", "Definitions")
    definition("**العمق** `Depth` عدد الطبقات ذات المعلمات (مخفية + إخراج). **العرض** `Width` عدد الوحدات في طبقة. **الشبكة العميقة** `Deep network` شبكة بأكثر من طبقة مخفية واحدة — «عميق» في «التعلم العميق». **الشبكة** `Network` تركيب الطبقات كله؛ **البنية** `Architecture` وصف هذا التركيب.")
    compare_table(["الزيادة في", "يزيد", "الفائدة", "المخاطر"],
                  [("العرض", "عدد الكواشف في الطبقة", "التقاط أنماط أكثر في نفس المستوى", "معلمات كثيرة، فرط تخصيص مع بيانات قليلة"),
                   ("العمق", "مستويات التجريد", "تركيب أنماط من أنماط (حواف ← أشكال ← أجسام)", "تلاشي التدرج، تدريب أصعب، حاجة إلى تنظيم وتهيئة جيدة")],
                  ["rtl", "rtl", "rtl", "rtl"])
    h2("العمق مقابل العرض بنفس عدد المعلمات", "Depth vs width at equal parameters")
    st.markdown("مقارنة مبسطة لعدد المعلمات ولـ«عدد المناطق الخطية» (مقياس تقريبي لتعبيرية شبكة ReLU) عند مدخل من 10 خصائص:")
    d = 10
    rows = []
    for name, sizes in [("عريضة: 10 → 256 → 1", [256]), ("متوسطة: 10 → 64 → 32 → 1", [64, 32]), ("عميقة: 10 → 32 → 32 → 32 → 1", [32, 32, 32])]:
        prev, params = d, 0
        for u in sizes:
            params += prev * u + u; prev = u
        params += prev + 1
        rows.append((name, str(params), str(len(sizes)), str(sum(sizes))))
    compare_table(["البنية", "المعلمات", "الطبقات المخفية", "مجموع الوحدات"], rows, ["ltr", "num", "num", "num"])
    research_note("نظريًا: شبكة ReLU عميقة تمثل بعض الدوال بعدد معلمات أسّيًا أقل من شبكة ضحلة عريضة (نتائج «كفاءة العمق»). عمليًا للجداول الصغيرة: 1–3 طبقات مخفية من 16–128 وحدة تكفي غالبًا، والأهم التنظيم والبيانات.")
    h2("قواعد عملية أولية", "Practical starting points")
    compare_table(["الحالة", "نقطة بداية معقولة", "ثم"],
                  [("جدول صغير (< 10k صف)، عشرات الخصائص", "طبقة مخفية واحدة أو اثنتان، 32–64 وحدة، ReLU", "وسّع إن كان قصور تعلم؛ نظّم إن كان فرط تخصيص"),
                   ("جدول كبير (100k+)", "2–4 طبقات، 64–256 وحدة", "راقب فجوة التدريب/التحقق"),
                   ("صور", "CNN (الأسبوع 08) لا كثيفة", "—"), ("تسلسل/سلاسل", "RNN/LSTM/GRU (الأسابيع 10–12)", "—")],
                  ["rtl", "rtl", "rtl"])
    practical_note("قاعدة التشخيص: **ابدأ بأصغر شبكة تتفوق على خط الأساس**. إن كانت خسارة التدريب نفسها مرتفعة فالقدرة ناقصة (وسّع/عمّق). إن كانت منخفضة والتحقق مرتفع فالقدرة زائدة أو التنظيم ناقص.")
    h2("أثر العمق على تركيب الخصائص", "Composition")
    st.markdown("مثال تخطيطي: شبكة 2 → 8 → 8 → 1 بـ ReLU تُنتج حدودًا أكثر تعقيدًا من 2 → 16 → 1 بنفس عدد الوحدات تقريبًا. جرّب ذلك عمليًا في **معمل بناء الشبكة** على بيانات الحلقة والحلزون.")
    common_mistake("«الأعمق أفضل دائمًا». شبكة من 10 طبقات على 500 صف جدولي تحفظ الضوضاء وتفشل في التعميم، وقد تعاني تلاشي التدرج. القدرة يجب أن تناسب البيانات.")
    quiz("arch.depth", [
        Q("شبكة 10 → 64 → 64 → 3: عمقها…", ["2", "3", "4"], 1, "طبقتان مخفيتان + إخراج."),
        Q("خسارة التدريب مرتفعة وخسارة التحقق مرتفعة وقريبة منها…", ["زد التنظيم", "زد القدرة (عرض/عمق)", "قلّل البيانات"], 1, "قصور تعلم."),
        Q("«عميق» في التعلم العميق يشير إلى…", ["عدد الوحدات", "عدد الطبقات", "حجم البيانات"], 1, "العمق."),
    ])
    takeaway("عمق = طبقات، عرض = وحدات. ابدأ صغيرًا، شخّص الفجوة، ثم وسّع أو نظّم. العمق يركّب الأنماط؛ العرض يوسّعها.")
    lesson_footer(LESSON, ["كلاهما معلمة فائقة.", "قصور تعلم ← زد القدرة؛ فرط تخصيص ← نظّم.", "للجداول الصغيرة: 1–3 طبقات تكفي غالبًا."])
