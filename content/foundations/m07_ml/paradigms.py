import streamlit as st

from components.callouts import common_mistake, definition, research_note, takeaway
from components.comparison import compare_table
from components.lesson_layout import h2, lesson_footer, lesson_header
from components.quiz import Q, quiz
from core.models import Lesson

LESSON = Lesson(
    id="foundations.ml.paradigms",
    title_ar="أنماط التعلم: مُشرف، غير مُشرف، شبه مُشرف، ذاتي الإشراف",
    title_en="Learning Paradigms: Supervised, Unsupervised, Semi- & Self-supervised",
    module="foundations.ml",
    order=1,
    prerequisites=["foundations.start.ai_ml_dl", "foundations.data.target"],
    objectives_ar=[
        "تحديد نمط التعلم من وجود الهدف وطبيعته.",
        "معرفة أن المقرر يركز على التعلم المُشرف، وأين يظهر الباقي (تمهيدًا).",
    ],
    terms=["target", "feature", "machine_learning"],
    difficulty="beginner",
    summary_ar="مُشرف: يوجد هدف y. غير مُشرف: لا هدف. شبه: هدف لبعض البيانات. ذاتي: الهدف يُشتق من البيانات نفسها.",
)


def render() -> None:
    lesson_header(LESSON)
    h2("السؤال الأول: هل يوجد هدف؟", "Is there a target?")
    definition("**التعلم المُشرف** `Supervised`: لكل ملاحظة هدف $y$ معلوم، والنموذج يتعلم $x \\to y$. **غير المُشرف** `Unsupervised`: لا هدف؛ نبحث عن بنية (عناقيد، تمثيلات مختصرة). **شبه المُشرف**: هدف لجزء صغير فقط. **ذاتي الإشراف** `Self-supervised`: نصنع الهدف من البيانات نفسها (تنبأ بالكلمة المحجوبة، بالإطار التالي) — أساس النماذج اللغوية الكبيرة.")
    compare_table(["النمط", "البيانات", "ماذا يتعلم", "أمثلة اقتصادية/إدارية", "في المقرر"],
                  [("مُشرف", "(x, y)", "دالة x → y", "التنبؤ بالتعثر، بالسعر، بالتضخم، تصنيف المراجعات", "الأساس: الأسابيع 01–15"),
                   ("غير مُشرف", "x فقط", "بنية / عناقيد / ضغط", "تقسيم العملاء إلى شرائح، اكتشاف الشذوذ في المعاملات", "تمهيد فقط"),
                   ("شبه مُشرف", "قليل من y", "استغلال غير الموسوم", "تصنيف آلاف الوثائق بعد وسم مئات", "تمهيد فقط"),
                   ("ذاتي الإشراف", "x بهدف مشتق", "تمثيلات عامة", "تمثيلات نصية مسبقة التدريب للتقارير المالية", "ملاحظة حديثة")],
                  ["rtl", "code", "rtl", "rtl", "rtl"])
    research_note("في البحث الاقتصادي غالبية المسائل مُشرفة (لدينا الهدف تاريخيًا). لكن الوسم يدوي مكلف في النص والصور — وهنا تفيد الأنماط الأخرى كمرحلة سابقة لتدريب مُشرف صغير.")
    common_mistake("«لدي بيانات كثيرة بلا هدف فسأدرّب شبكة عميقة». بلا هدف لا يوجد تعلم مُشرف؛ يجب إما وسم جزء، أو صياغة مهمة ذاتية الإشراف، أو استخدام طرق غير مُشرفة.")
    quiz("ml.paradigms", [
        Q("بيانات عملاء بلا أي عمود هدف، نريد شرائح. النمط؟", ["مُشرف", "غير مُشرف", "ذاتي الإشراف"], 1, "لا y."),
        Q("«تنبأ بالكلمة المحجوبة في الجملة» هو…", ["مُشرف تقليدي", "ذاتي الإشراف", "غير مُشرف"], 1, "الهدف مشتق من البيانات."),
        Q("جدول بأعمدة x وعمود y معلوم للجميع…", ["مُشرف", "شبه مُشرف", "غير مُشرف"], 0, "الأساس."),
    ])
    takeaway("وجود الهدف وطبيعته يحددان النمط. المقرر مُشرف؛ الباقي تمهيد للسياق.")
    lesson_footer(LESSON, ["مُشرف = x و y.", "غير مُشرف = بنية بلا y.", "ذاتي الإشراف = y مصنوع من x."])
