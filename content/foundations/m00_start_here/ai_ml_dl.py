def render() -> None:
    lesson_header(LESSON)

    h2("ما المشكلة التي نحلها؟", "What problem are we solving?")
    st.markdown(
        """
كثيرًا ما تُستخدم الكلمات الثلاث **الذكاء الاصطناعي** و**التعلم الآلي** و**التعلم العميق** كمرادفات في
الإعلام والعروض التقديمية. في البحث العلمي هذا خطأ يؤدي إلى مطالبات غير دقيقة وإلى اختيار أدوات
غير مناسبة. هذا الدرس يرسم الحدود بدقة.
"""
    )

    h2("التعريفات", "Definitions")
    definition(
        "**الذكاء الاصطناعي** `Artificial Intelligence (AI)`: أي نظام حاسوبي يؤدي مهمة نعدّها تحتاج إلى ذكاء "
        "بشري: التخطيط، الاستدلال المنطقي، البحث، فهم اللغة، الرؤية... **لا يشترط أن يتعلم من البيانات**؛ "
        "نظام خبير مبني على قواعد `if/else` مكتوبة يدويًا هو ذكاء اصطناعي.",
        "الذكاء الاصطناعي",
    )
    definition(
        "**التعلم الآلي** `Machine Learning (ML)`: فرع من الذكاء الاصطناعي **تُستخرج فيه القواعد من البيانات** "
        "بدل كتابتها يدويًا. نعطي الخوارزمية أمثلة (مدخلات ومخرجات) فتبني **نموذجًا** يعمّم على أمثلة جديدة. "
        "الانحدار الخطي، أشجار القرار، الغابات العشوائية... كلها تعلم آلي.",
        "التعلم الآلي",
    )
    definition(
        "**التعلم العميق** `Deep Learning (DL)`: فرع من التعلم الآلي يستخدم **شبكات عصبية متعددة الطبقات** "
        "تتعلم **التمثيلات/الخصائص بنفسها** من البيانات الخام، بدل أن يصممها الباحث يدويًا. كلمة «عميق» تشير "
        "إلى عدد الطبقات المتتالية.",
        "التعلم العميق",
    )

    h2("الشرح البصري", "Visual explanation")
    diagram(
        "علاقة الاحتواء بين المفاهيم الثلاثة",
        _nested_svg(),
        what_ar="ثلاث دوائر متداخلة: الأكبر هو الذكاء الاصطناعي، بداخله التعلم الآلي، وبداخله التعلم العميق.",
        how_ar="كل ما هو تعلم عميق هو تعلم آلي، وكل تعلم آلي هو ذكاء اصطناعي. العكس غير صحيح: هناك ذكاء اصطناعي لا يتعلم، وتعلم آلي لا يستخدم شبكات عصبية.",
        takeaway_ar="التعلم العميق حالة خاصة، مكلفة وقوية، وليس المرادف الوحيد للذكاء الاصطناعي.",
        legend=[("#E6F1FB", "الذكاء الاصطناعي"), ("#DDF5EA", "التعلم الآلي"), ("#EFE9FA", "التعلم العميق")],
        title_en="AI ⊃ ML ⊃ DL",
    )

    h2("الفرق الجوهري: من يصمم الخصائص؟", "Who designs the features?")
    intuition(
        "تخيل أنك تريد التنبؤ بتعثر عميل في سداد قرض. في **التعلم الآلي التقليدي** أنت من يقرر الخصائص "
        "(`Features`): الدخل، نسبة الدين إلى الدخل، عدد التأخيرات السابقة... ثم تعطيها للنموذج. "
        "في **التعلم العميق** يمكنك إعطاء الشبكة البيانات الأقل معالجة (مثلًا تسلسل المعاملات الشهرية الخام) "
        "وتترك الطبقات الأولى تكتشف الخصائص المفيدة بنفسها."
    )
    compare_table(
        ["الجانب", "Traditional ML", "Deep Learning"],
        [
            ("الخصائص", "Hand-crafted by the researcher", "Learned automatically by layers"),
            ("حجم البيانات المطلوب", "Small to medium", "Usually large"),
            ("قابلية التفسير", "Often high (coefficients, trees)", "Lower; needs special tools"),
            ("الحوسبة", "CPU is often enough", "GPU often needed"),
            ("البيانات المناسبة", "Tabular, structured", "Images, text, audio, sequences, large tabular"),
            ("أمثلة", "Linear/Logistic Regression, Random Forest, XGBoost", "MLP, CNN, RNN/LSTM/GRU, Transformers"),
        ],
        ["rtl", "ltr", "ltr"],
    )

    h2("متى يكون التعلم العميق خيارًا مناسبًا؟", "When is DL the right tool?")
    c1, c2 = st.columns(2)
    with c1:
        with st.container(border=True):
            st.markdown("**✅ مناسب غالبًا عندما:**")
            st.markdown(
                """
- البيانات غير مهيكلة: صور، نصوص، صوت، سلاسل زمنية طويلة.
- حجم البيانات كبير (آلاف إلى ملايين الأمثلة).
- العلاقة بين المدخلات والمخرجات معقدة ولا خطية.
- توجد موارد حوسبة (GPU) ووقت لضبط المعلمات الفائقة.
"""
            )
    with c2:
        with st.container(border=True):
            st.markdown("**❌ غير مناسب غالبًا عندما:**")
            st.markdown(
                """
- بيانات جدولية صغيرة (مئات الصفوف) — الانحدار أو الأشجار أفضل وأوضح.
- المطلوب تفسير سببي أو معاملات قابلة للتأويل الاقتصادي.
- لا يوجد خط أساس (`Baseline`) بسيط للمقارنة بعد.
- التكلفة الحسابية لا تبررها الدقة الإضافية.
"""
            )
    common_mistake(
        "«جربت شبكة عصبية على 200 صف من بيانات مسح فأعطت نتائج أسوأ من الانحدار اللوجستي». هذا متوقع "
        "وليس فشلًا في الشبكة؛ الشبكات العميقة تحتاج بيانات أكثر وتنظيمًا أقوى. ابدأ دائمًا بخط أساس بسيط."
    )

    h2("تطبيقات في التخصصات الاقتصادية والإدارية", "Applications in economics & management")
    compare_table(
        ["المجال", "المهمة", "النوع", "بنية مناسبة"],
        [
            ("التمويل", "التنبؤ بتعثر القروض من بيانات العملاء", "تصنيف ثنائي", "MLP / Gradient Boosting"),
            ("الاقتصاد الكلي", "التنبؤ بالتضخم من سلاسل زمنية متعددة", "انحدار زمني", "LSTM / GRU"),
            ("التسويق", "تحليل مشاعر مراجعات العملاء", "تصنيف نصوص", "RNN / Transformers"),
            ("الإدارة", "التنبؤ بترك الموظفين للعمل", "تصنيف ثنائي", "MLP"),
            ("سلاسل الإمداد", "التنبؤ بالطلب اليومي", "انحدار زمني", "GRU / LSTM"),
            ("المحاسبة", "كشف الاحتيال في المعاملات", "تصنيف غير متوازن", "MLP + معالجة عدم التوازن"),
            ("العقارات", "تقدير السعر من صور ووصف العقار", "انحدار متعدد الوسائط", "CNN + MLP"),
        ],
        ["rtl", "rtl", "rtl", "ltr"],
    )
    research_note(
        "نموذج تنبؤي دقيق **لا يثبت سببية**. أن الشبكة تتنبأ بالتعثر من «عدد المكالمات مع خدمة العملاء» "
        "لا يعني أن المكالمات تسبب التعثر. سنفرد لهذا التمييز درسًا في نزاهة البحث."
    )

    h3("مقارنة سريعة: نموذج / خوارزمية / بنية", "Model vs Algorithm vs Architecture")
    compare_table(
        ["المصطلح", "English", "المعنى", "مثال"],
        [
            ("النموذج", "Model", "الدالة النهائية ذات المعلمات المحددة التي تحوّل مدخلًا إلى تنبؤ", "شبكة مدرَّبة بأوزان محددة"),
            ("الخوارزمية", "Algorithm", "الإجراء الذي يُنتج أو يدرّب النموذج", "الانحدار التدريجي، Adam"),
            ("البنية", "Architecture", "تصميم النموذج قبل التدريب: الطبقات وعددها وروابطها", "MLP بطبقتين مخفيتين، CNN"),
        ],
        ["rtl", "ltr", "rtl", "rtl"],
    )
    why("لماذا هذا التمييز مهم؟ لأنك عندما تقول «النموذج لا يتعلم» يجب أن تعرف هل المشكلة في البنية، أم في خوارزمية التدريب، أم في البيانات.")

    quiz(
        "start.ai_ml_dl",
        [
            Q("أي العبارات صحيحة؟",
              ["كل ذكاء اصطناعي هو تعلم عميق", "كل تعلم عميق هو تعلم آلي", "التعلم الآلي والتعلم العميق مترادفان"], 1,
              "التعلم العميق حالة خاصة من التعلم الآلي."),
            Q("ما الفرق الجوهري بين التعلم الآلي التقليدي والتعلم العميق؟",
              ["التعلم العميق لا يحتاج إلى بيانات", "في التعلم العميق تتعلم الطبقات الخصائص بنفسها",
               "التعلم الآلي التقليدي لا يستخدم الرياضيات"], 1,
              "التمثيلات تُتعلم تلقائيًا بدل تصميمها يدويًا."),
            Q("لديك 300 صف من بيانات مسح جدولية وتريد نموذجًا قابلًا للتفسير. ما الخيار الأنسب للبدء؟",
              ["شبكة عصبية عميقة بعشر طبقات", "انحدار لوجستي أو شجرة قرار كخط أساس", "LSTM"], 1,
              "بيانات صغيرة جدولية + تفسير = ابدأ ببساطة."),
            Q("نظام يعتمد على قواعد مكتوبة يدويًا لتصنيف الطلبات. هل هو ذكاء اصطناعي؟",
              ["نعم، لكنه ليس تعلمًا آليًا", "لا، لأنه لا يتعلم", "نعم، وهو تعلم عميق"], 0,
              "الذكاء الاصطناعي لا يشترط التعلم من البيانات."),
        ],
    )
    takeaway("AI ⊃ ML ⊃ DL. التعلم العميق يتعلم الخصائص بنفسه لكنه يحتاج بيانات وحوسبة أكثر، وليس دائمًا الخيار الأفضل.")
    lesson_footer(LESSON, [
        "الذكاء الاصطناعي: أي نظام يؤدي مهمة «ذكية»، ولو بقواعد يدوية.",
        "التعلم الآلي: استخراج القواعد (النموذج) من البيانات.",
        "التعلم العميق: شبكات متعددة الطبقات تتعلم الخصائص تلقائيًا.",
        "ابدأ بخط أساس بسيط قبل أي شبكة عميقة، خاصة مع بيانات جدولية صغيرة.",
    ])
