import pandas as pd
import streamlit as st

from components.callouts import common_mistake, definition, intuition, research_note, takeaway, why
from components.lesson_layout import h2, lesson_footer, lesson_header
from components.quiz import Q, quiz
from core.models import Lesson
from core.rtl import table

LESSON = Lesson(
    id="foundations.data.what_is_data",
    title_ar="ما هي البيانات؟",
    title_en="What is Data?",
    module="foundations.data",
    order=1,
    prerequisites=["foundations.start.model_training_prediction"],
    objectives_ar=[
        "تعريف البيانات كقياسات مسجلة عن كيانات.",
        "التمييز بين البيانات الخام والبيانات المنظمة الجاهزة للنموذج.",
        "رؤية أن كل ما يدخل الشبكة يجب أن يصبح أرقامًا في النهاية.",
    ],
    terms=["data", "dataset", "observation", "feature"],
    related=["foundations.data.dataset"],
    difficulty="beginner",
    summary_ar="البيانات قياسات مسجلة؛ الشبكة لا تقبل إلا أرقامًا مرتبة في موترات.",
)


def render() -> None:
    lesson_header(LESSON)
    h2("ما هي؟", "What is it?")
    definition(
        "**البيانات** `Data` هي **قياسات أو تسجيلات** عن كيانات من العالم: عملاء، شركات، أيام تداول، "
        "صور، جمل. كل قياس يجيب عن سؤال محدد (كم الدخل؟ ما اللون؟ هل سدد؟) عن كيان محدد."
    )
    why(
        "النموذج لا يرى العالم؛ يرى فقط ما سجّلناه. إذا لم نسجل «عدد التأخيرات السابقة» فلا يمكن "
        "لأي شبكة، مهما كانت عميقة، أن تستخدم هذه المعلومة."
    )
    h2("الحدس", "Intuition")
    intuition(
        "فكر في استبيان: كل ورقة مملوءة = كيان واحد، وكل سؤال = قياس. عندما نصف الأوراق فوق بعضها "
        "ونرتب الأسئلة كأعمدة نحصل على **جدول**. هذا الجدول هو الشكل الذي تحبه النماذج."
    )
    st.markdown("**مثال: بيانات عملاء بنك (5 عملاء، 4 قياسات لكل عميل):**")
    df = pd.DataFrame({
        "customer_id": [101, 102, 103, 104, 105],
        "income": [4200, 6100, 2900, 8800, 5100],
        "num_late_payments": [0, 2, 5, 0, 1],
        "city": ["Algiers", "Oran", "Algiers", "Constantine", "Oran"],
        "defaulted": [0, 0, 1, 0, 0],
    })
    st.dataframe(df, hide_index=True, width="stretch")
    st.markdown(
        """
- كل **صف** عميل واحد (سنسميه لاحقًا **ملاحظة** `Observation`).
- كل **عمود** قياس واحد (سنسميه **خاصية** `Feature` إذا كان مدخلًا، أو **هدف** `Target` إذا كان ما نريد التنبؤ به).
- العمود `defaulted` هو الهدف هنا: هل تعثر العميل؟
"""
    )
    h2("خام أم منظمة؟", "Raw vs prepared")
    table(
        ["الحالة", "English", "مثال", "هل يقبلها النموذج مباشرة؟"],
        [
            ("خام", "Raw data", "ملفات PDF لكشوف حساب، تسجيلات صوتية، صور", "لا"),
            ("منظمة", "Structured / tabular", "جدول صفوفه ملاحظات وأعمدته قياسات", "تقريبًا (بعد التحويل إلى أرقام)"),
            ("جاهزة للنموذج", "Model-ready tensors", "`X` بالشكل `(n, d)` أرقامًا فقط، و`y` بالشكل `(n,)`", "نعم"),
        ],
        ["rtl", "ltr", "rtl", "rtl"],
    )
    st.markdown(
        """
الشبكة العصبية تقبل **أرقامًا فقط** مرتبة في **موترات** `Tensors`. لذلك المدينة `Algiers` يجب أن تتحول إلى
أرقام (ترميز)، والصورة تتحول إلى مصفوفة قيم بكسل، والنص إلى أرقام تمثل الكلمات. سنشرح كل تحويل في وحدة إعداد البيانات.
"""
    )
    common_mistake(
        "تمرير عمود نصي مثل `city` إلى `Keras` مباشرة يعطي خطأ من نوع `ValueError: could not convert string to float`. "
        "الخطأ ليس في الشبكة بل في أن البيانات ليست أرقامًا بعد."
    )
    research_note(
        "في البحوث الاقتصادية غالبًا ما تكون «البيانات» جداول من مصادر رسمية (بنك مركزي، مكتب إحصاء). "
        "ميزة كبيرة: منظمة. عيب شائع: قليلة (عشرات إلى مئات الصفوف)، وهذا يقيّد اختيار النموذج."
    )
    quiz(
        "data.what_is_data",
        [
            Q("ما الذي يراه النموذج من العالم؟", ["كل ما يحدث", "ما سُجّل فقط", "ما يفهمه الباحث"], 1, "البيانات هي القياسات المسجلة فقط."),
            Q("في جدول العملاء، ما الصف الواحد؟", ["قياس واحد", "عميل واحد", "الهدف"], 1, "الصف = ملاحظة = كيان واحد."),
            Q("لماذا يفشل تمرير `city='Algiers'` إلى الشبكة؟", ["لأن المدينة غير مهمة", "لأن الشبكة تقبل أرقامًا فقط", "لأن الاسم طويل"], 1, "يجب الترميز أولًا."),
        ],
    )
    takeaway("البيانات قياسات عن كيانات. الجدول (صفوف = كيانات، أعمدة = قياسات) هو نقطة البداية، والأرقام في موترات هي نقطة النهاية.")
    lesson_footer(LESSON, [
        "البيانات = قياسات مسجلة عن كيانات.",
        "صف = ملاحظة، عمود = قياس (خاصية أو هدف).",
        "الشبكة تقبل أرقامًا فقط في موترات ذات شكل محدد.",
    ])
