        "الهدف أيضًا له نوع: عددي ← انحدار؛ ثنائي ← تصنيف ثنائي؛ اسمي متعدد ← تصنيف متعدد الفئات. "
        "هدف ترتيبي (ضعيف/متوسط/جيد) حالة خاصة تُعامل غالبًا كتصنيف متعدد الفئات في المقرر."
