LESSON = Lesson(
    id="foundations.neuron.weighted_sum_bias",
    title_ar="الوزن والانحياز والمجموع الموزون",
    title_en="Weight, Bias & the Weighted Sum",
    module="foundations.neuron",
    order=2,
    prerequisites=["foundations.neuron.line_to_neuron"],
    objectives_ar=["تفسير إشارة الوزن وحجمه كأثر واتجاه.", "فهم دور الانحياز كإزاحة تحدد «نقطة التشغيل».", "حساب المجموع الموزون يدويًا وبالكود لملاحظة ولدفعة."],
    terms=["weight", "bias", "dot_product"],
    labs=["labs.neuron_lab"],
    difficulty="beginner",
    summary_ar="الوزن أثر واتجاه لكل مدخل؛ الانحياز إزاحة؛ z = w·x + b ملخص الأدلة في رقم.",
)

CODE = '''import numpy as np
# خلية تقيّم عميلًا من 3 خصائص موحدة: [الدخل, التأخيرات, نسبة الدين]
w = np.array([-0.8, 1.5, 1.1])     # أوزان: سالب = يقلل خطر التعثر، موجب = يزيده
b = {b}

customers = np.array([[ 1.2, -0.5, -0.8],    # دخل مرتفع، تأخيرات قليلة، دين منخفض
                      [-1.0,  2.0,  0.9],    # دخل منخفض، تأخيرات كثيرة، دين مرتفع
                      [ 0.0,  0.0,  0.0]])   # عميل "متوسط" تمامًا
for i, x in enumerate(customers):
    contributions = w * x
    z = contributions.sum() + b
    print(f"customer {i}: contributions={contributions.round(2)}  z = {contributions.sum():+.2f} + b({b}) = {z:+.2f}")

# للدفعة كلها في سطر واحد
print("z (batch) =", (customers @ w + b).round(2))'''


def _controls() -> dict:
    return {"b": st.slider("الانحياز b", -3.0, 3.0, -0.5, 0.25, key="ctrl_ws_b")}


def render() -> None:
    lesson_header(LESSON)
    h2("الوزن", "Weight")
    definition("**الوزن** $w_j$ رقم يضرب الخاصية $x_j$. **إشارته** اتجاه الأثر (موجب يرفع $z$، سالب يخفضه)، و**حجمه** قوة الأثر. يتعلمه التدريب.")
    intuition("الأوزان «آراء» الخلية عن كل خاصية: «التأخيرات دليل قوي على الخطر (+1.5)»، «الدخل المرتفع دليل ضد الخطر (−0.8)». الضرب في القيمة يحوّل الرأي إلى تصويت موزون.")
    h2("الانحياز", "Bias")
    definition("**الانحياز** $b$ رقم يُضاف بعد المجموع الموزون. يحدد قيمة $z$ عندما تكون كل المدخلات صفرًا، أي «الميل الافتراضي» للخلية قبل النظر إلى الأدلة. بدونه يُجبر الحد الفاصل على المرور بالأصل.")
    why("لماذا لا نستغني عن الانحياز؟ خلية بـ Sigmoid بلا انحياز تعطي 0.5 بالضبط لكل مدخل صفري — لا تستطيع القول «معظم العملاء لا يتعثرون». الانحياز يحمل معدل الأساس.")
    h2("المجموع الموزون", "Weighted sum")
    equation(r"z = \sum_{j=1}^{d} w_j x_j + b", [("w_j x_j", "مساهمة الخاصية $j$: رأي × قيمة."), (r"\sum", "جمع المساهمات."), ("b", "الإزاحة.")],
             meaning_ar="رقم واحد يلخص كل الأدلة. موجب كبير = «نعم بقوة»، سالب كبير = «لا بقوة»، قرب الصفر = «غير محسوم».",
             example_ar="$w = (-0.8, 1.5, 1.1)$، $x = (1.2, -0.5, -0.8)$، $b = -0.5$: $z = -0.96 - 0.75 - 0.88 - 0.5 = -3.09$.",
             dl_link_ar="يُسمى أيضًا `pre-activation` أو `logit`. الطبقة الكثيفة تحسب $d \\times k$ من هذه المجاميع دفعة واحدة.", title_ar="المجموع الموزون")
    worked_steps([("المساهمات", r"(-0.8)(1.2) = -0.96,\ (1.5)(-0.5) = -0.75,\ (1.1)(-0.8) = -0.88"), ("المجموع", r"-0.96 - 0.75 - 0.88 = -2.59"), ("مع الانحياز", r"z = -2.59 + (-0.5) = -3.09")])
    code_lab(CodeLab(
        key="neuron_ws", title_ar="مساهمات كل خاصية ثم المجموع لثلاثة عملاء", code=CODE, template=True, defaults={"b": -0.5},
        before=Before(goal_ar="رؤية كيف تُبنى $z$ من مساهمات فردية، وأثر الانحياز على العميل «المتوسط».", stage_ar="الخلية العصبية.",
                      inputs_ar="أوزان ثابتة، انحياز من عنصر التحكم، 3 عملاء بخصائص موحدة.", expected_ar="مساهمات لكل خاصية، z لكل عميل، ثم z للدفعة بسطر واحد."),
        explain=[("3-4", "أوزان بإشارات ذات معنى اقتصادي. الانحياز من عنصر التحكم."), ("6-9", "ثلاثة عملاء؛ الثالث كله أصفار فمخرجه = الانحياز فقط."),
                 ("10-13", "الضرب العنصري يعطي المساهمات؛ جمعها + b = z. الطباعة تُظهر أي خاصية رجّحت الكفة."), ("16", "الدفعة: `X @ w + b`.")],
        controls=_controls, run=run_printed(CODE, template=True),
        after_ar="- العميل 2 (كل شيء صفر) يعطي `z = b` بالضبط: الانحياز هو حكم الخلية بلا أدلة.\n- حرّك b: كل قيم z تنزاح بنفس المقدار — الانحياز لا يغيّر ترتيب العملاء، بل العتبة الفعلية.",
    ))
    h3("جدول التفسير", "Interpretation table")
    table(["الكمية", "قيمة كبيرة موجبة", "قريبة من الصفر", "كبيرة سالبة"],
          [("الوزن w_j", "الخاصية ترفع z بقوة", "الخاصية شبه مهملة", "الخاصية تخفض z بقوة"), ("الانحياز b", "الخلية تميل إلى «نعم» افتراضيًا", "محايدة", "تميل إلى «لا» افتراضيًا"),
           ("المجموع z", "قرار قوي بـ «نعم»", "غير محسوم", "قرار قوي بـ «لا»")], ["rtl", "rtl", "rtl", "rtl"])
    common_mistake("تفسير أوزان خلية في شبكة عميقة كما تُفسَّر معاملات الانحدار: في الطبقات المخفية الأوزان تتفاعل عبر طبقات ولا تحمل تفسيرًا مباشرًا. التفسير أعلاه صالح للخلية الواحدة (الانحدار اللوجستي).")
    quiz("neuron.ws", [
        Q("وزن −2.3 لخاصية يعني…", ["الخاصية غير مهمة", "زيادتها تخفض z بقوة", "زيادتها ترفع z"], 1, "إشارة سالبة كبيرة."),
        Q("مدخل كله أصفار: z يساوي…", ["0", "b", "مجموع الأوزان"], 1, "الانحياز."),
        Q("بلا انحياز، الحد الفاصل…", ["يمر بالأصل إجباريًا", "يختفي", "يصبح منحنيًا"], 0, "قيد غير مبرر."),
    ])
    takeaway("z = w·x + b: أوزان = آراء موزونة، انحياز = ميل افتراضي، z = ملخص الأدلة.")
    lesson_footer(LESSON, ["إشارة الوزن اتجاه، حجمه قوة.", "الانحياز = z عند مدخل صفري.", "X @ w + b للدفعة."])
