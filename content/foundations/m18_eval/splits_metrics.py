import streamlit as st

from components.callouts import common_mistake, definition, practical_note, takeaway
from components.comparison import compare_table
from components.lesson_layout import h2, lesson_footer, lesson_header
from components.quiz import Q, quiz
from core.models import Lesson

LESSON = Lesson(
    id="foundations.eval.splits_metrics",
    title_ar="مقاييس التدريب والتحقق والاختبار: ماذا يُقاس وأين ولماذا",
    title_en="Train / Validation / Test Metrics: What, Where, Why",
    module="foundations.eval",
    order=1,
    prerequisites=["foundations.ml.baseline_generalization", "foundations.training_loop.validation_in_loop"],
    objectives_ar=["تحديد أي رقم يُبلَّغ عنه ومن أي مجموعة.", "فهم أن خسارة التدريب مقياس تحسين، ومقياس الاختبار مقياس تقرير.", "قواعد التقرير الصادق: مرة واحدة، بعدة بذور، مع خط الأساس."],
    terms=["loss"],
    difficulty="beginner",
    summary_ar="التدريب للتشخيص، التحقق للاختيار، الاختبار للتقرير مرة واحدة. أبلغ عن المقياس مع خط الأساس والتباين.",
)


def render() -> None:
    lesson_header(LESSON)
    h2("ثلاث مجموعات، ثلاثة أدوار", "Three sets, three roles")
    compare_table(["المجموعة", "ما نقيسه", "الاستخدام", "كم مرة", "الرقم في التقرير؟"],
                  [("التدريب", "loss، metric", "تشخيص: هل يتعلم؟ قصور؟", "كل حقبة", "لا (إلا للفجوة)"), ("التحقق", "val_loss، val_metric", "اختيار المعلمات الفائقة، الإيقاف المبكر، اختيار النموذج", "كل حقبة/تجربة", "كمؤشر تطوير فقط"),
                   ("الاختبار", "المقياس النهائي", "تقدير الأداء على بيانات جديدة", "مرة واحدة في النهاية", "نعم — هذا هو الرقم")],
                  ["rtl", "code", "rtl", "rtl", "rtl"])
    definition("**الفجوة** بين مقياس التدريب والتحقق هي التشخيص الأول (فرط تخصيص/قصور تعلم). **الفجوة** بين التحقق والاختبار تكشف إن كان الاختيار المفرط على التحقق قد ضخّم رقمه (overfitting to validation).")
    h2("قواعد التقرير", "Reporting rules")
    st.markdown("""
1. **خط الأساس** في السطر الأول: الفئة الأغلب / المتوسط / نموذج بسيط.
2. **الاختبار مرة واحدة**؛ إن غيّرت شيئًا بعد رؤيته فقد صار تحققًا.
3. **عدة بذور** (3–5) وأبلغ عن المتوسط ± الانحراف.
4. **المقياس المناسب للمهمة** (الدروس التالية)، مع الخسارة كمعلومة ثانوية.
5. **المنحنيات** (تدريب/تحقق) في الملحق: تكشف ما لا يكشفه رقم.
""")
    practical_note("جملة تقرير نموذجية: «على مجموعة اختبار محجوزة (n = 1,200)، حقق النموذج F1 = 0.71 ± 0.02 عبر 5 بذور مقابل 0.00 لخط الأساس (الفئة الأغلب) و0.63 للانحدار اللوجستي».")
    common_mistake("الإبلاغ عن أفضل حقبة على التحقق كأنها نتيجة الاختبار، أو عن أفضل بذرة من عشر. كلاهما تفاؤل منهجي.")
    quiz("eval.splits", [
        Q("الرقم الذي يظهر في ملخص الورقة يأتي من…", ["التدريب", "التحقق", "الاختبار"], 2, "التقرير."),
        Q("فجوة كبيرة بين التحقق والاختبار تعني غالبًا…", ["تسريب في الاختبار", "اختيار مفرط على التحقق", "خطأ في الكود"], 1, "التحقق صار جزءًا من التدريب."),
        Q("لماذا عدة بذور؟", ["للسرعة", "لتقدير التباين وتجنب الحظ", "لا حاجة"], 1, "النتيجة الواحدة قد تكون صدفة."),
    ])
    takeaway("تدريب = تشخيص، تحقق = اختيار، اختبار = تقرير مرة واحدة بعدة بذور مع خط الأساس.")
    lesson_footer(LESSON, ["أدوار المجموعات الثلاث.", "خمس قواعد للتقرير.", "الفجوات كتشخيص."])
