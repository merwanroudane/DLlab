    layers.Input(shape=(max_len,)),                              # (n, T) أعداد صحيحة بحشو
    layers.Embedding(vocab_size, 64, mask_zero=True),            # (n, T, 64): تضمين متعلَّم لكل كلمة؛ mask_zero يتجاهل الحشو
