    ("10. التدريب", "الكود الكامل، الإيقاف المبكر، الحفظ، الزمن والجهاز (CPU/Colab GPU).", "الأسبوعان 03 و13", "تدريب بلا حفظ نقاط"),
    ("11. المنحنيات", "loss/val_loss (والمقياس) عبر الحقب، أفضل حقبة، الفجوة.", "الأسس 19", "قراءة الخسارة الموحَّدة كنتيجة"),
