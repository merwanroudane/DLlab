def render() -> None:
    lesson_header(LESSON)
    why("المشروع يُقيَّم بالمنهج لا بالدقة: مشروع بدقة 70% بخط أساس وتشخيص واستنساخ يتفوق على مشروع بدقة 95% بلا خط أساس (قد تكون تسريبًا). الدليل يجعل كل مرحلة سؤالًا يجاب عنه في التقرير.")
    pipeline([s[0].split(". ")[1] for s in STAGES[:6]], active=0)
    pipeline([s[0].split(". ")[1] for s in STAGES[6:12]], active=None)
    pipeline([s[0].split(". ")[1] for s in STAGES[12:]], active=None)
    h2("خريطة الطريق: 17 محطة في أربع مراحل", "The roadmap: 17 stops in four phases")
    phase_ar = {"Plan": "التخطيط", "Build": "البناء", "Diagnose": "التشخيص", "Report": "التقرير"}
    rcaps = []
    for i, (name, what, ref, mistake) in enumerate(STAGES):
        ph, _ = phase_of(i)
        rcaps.append(f"**{name}** (مرحلة {phase_ar[ph]}): {what} — **الخطأ الشائع**: {mistake}.")
    animation_player("w14_roadmap", [Frame(roadmap_svg(STAGES, i), caption(c), action=STAGES[i][0].split('. ', 1)[1]) for i, c in enumerate(rcaps)],
                     title_ar="المشروع من السؤال إلى العرض", stages=["التخطيط 1–6", "البناء 7–10", "التشخيص 11–13", "التقرير 14–17"], interval_ms=2600)
    st.caption("لاحظ: النموذج نفسه (المرحلة 8) يأتي بعد سبع مراحل من التفكير في البيانات والتقسيم وخط الأساس.")
    h2("اختيار نوع المشروع", "Choosing the project type")
    compare_table(["بياناتك", "المسألة النموذجية", "البنية", "خط الأساس", "الأسابيع المرجعية", "حجم كافٍ"],
                  [("جدول (عملاء، شركات، عقارات)", "تصنيف تعثر/مغادرة، تنبؤ سعر/طلب", "MLP صغير", "لوجستي/خطي، أشجار", "02–07", "بضع مئات صف"), ("صور (منتجات، رسوم بيانية، مستندات)", "تصنيف صور", "CNN صغيرة (+ زيادة بيانات)", "الأغلبية؛ لوجستي على البكسلات", "08–09", "بضع مئات صورة لكل فئة"),
                   ("سلسلة زمنية (مبيعات، طاقة، أسعار)", "تنبؤ القيمة/الاتجاه القادم", "GRU/LSTM (+ SimpleRNN)", "الساذج، المتوسط الموسمي، خطي", "10–12", "بضع مئات نافذة"), ("نص (شكاوى، مراجعات)", "تصنيف نص", "Embedding + GRU ثنائي الاتجاه", "حقيبة كلمات + لوجستي", "11–12", "بضع مئات نص لكل فئة")],
                  ["rtl", "rtl", "rtl", "rtl", "code", "rtl"])
    practical_note("اختر ما تملك بياناته **الآن**. مشروع جدولي بـ 400 صف ومنهج كامل ممتاز؛ مشروع صور طموح ببيانات لم تُجمع فاشل. الطموح في المنهج لا في حجم النموذج.")
    h2("المراحل السبع عشرة", "The seventeen stages")
    st.session_state.setdefault("w14_check", {})
    done = 0
    for name, what, ref, mistake in STAGES:
        with st.container(border=True):
            c1, c2 = st.columns([4, 1.2], vertical_alignment="top")
            with c1:
                st.markdown(f"**{name}** — {what}")
                st.caption(f"المرجع: {ref} · الخطأ الشائع: {mistake}")
            with c2:
                st.session_state["w14_check"][name] = st.checkbox("منجز", value=st.session_state["w14_check"].get(name, False), key=f"w14_chk_{name}")
        done += int(st.session_state["w14_check"][name])
    st.progress(done / len(STAGES), text=f"{done} / {len(STAGES)} مرحلة")
    intuition("كل مرحلة تنتج **قطعة من التقرير**. إن كتبت المراحل الست الأولى بوضوح فقد أنجزت نصف المشروع؛ النموذج يأتي في المرحلة 8 لا في الأولى.")
    research_note("**المعلمات الفائقة (المرحلة 9)**: جدول صغير من 3–6 تجارب على التحقق يكفي (η × 3 قيم، البنية × 2). لا حاجة لبحث شبكي واسع؛ أبلغ ما جُرّب وما اختير ولماذا. وكل تجربة بنفس التقسيم والبذرة.")
    with st.container(horizontal=True):
        st.button("قالب الدفتر", icon=":material/description:", type="primary", on_click=goto, args=("course.w14.notebook_template",), key="w14_go_template")
        st.button("الأسبوع 07 — القالب المصغّر", icon=":material/menu_book:", on_click=goto, args=("course.w07.build_pipeline",), key="w14_go_w07")
        st.button("الرمز النهائي (الأسبوع 15)", icon=":material/grading:", on_click=goto, args=("course.w15.rubric",), key="w14_go_rubric")
    common_mistake("«سأبدأ بالنموذج ثم أكتب التقرير في النهاية». التقرير هو ما يوجّه القرارات؛ اكتب المراحل 1–7 قبل أي سطر Keras.")
    quiz("w14.guide", [
        Q("أول مرحلة تنتج نموذجًا:", ["1", "7 (خط الأساس)", "10"], 1, ""),
        Q("جدول المعلمات الفائقة يُبنى على…", ["التدريب", "التحقق", "الاختبار"], 1, ""),
        Q("سلسلة زمنية: خط الأساس الإلزامي", ["MLP", "الساذج والموسمي", "CNN"], 1, ""),
        Q("مشروع بدقة 95% بلا خط أساس مقابل 70% بمنهج كامل:", ["الأول أفضل", "الثاني أفضل: الأول قد يكون تسريبًا", "متساويان"], 1, ""),
    ])
    takeaway("17 مرحلة = 17 قطعة في التقرير. البيانات تحدد البنية وخط الأساس. المنهج يُقيَّم لا الدقة. ابدأ بالمراحل 1–7 قبل النموذج.")
    lesson_footer(LESSON, ["اختيار النوع بحسب البيانات.", "المراحل بقائمة فحص.", "الروابط إلى القالب والرمز."])
