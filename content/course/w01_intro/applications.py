import plotly.graph_objects as go_fig
import streamlit as st

from components.animation_player import Frame, animation_player, caption
from components.callouts import common_mistake, interpretation_note, research_note, takeaway, warning_note
from components.comparison import compare_table
from components.lesson_layout import h2, h3, lesson_footer, lesson_header
from components.quiz import Q, quiz
from content.course.w01_intro._viz import confounding_demo, loan_preview, loan_task_svg, size_experiment
from core.models import Lesson

LESSON = Lesson(
    id="course.w01.applications",
    title_ar="التطبيقات في التخصصات الاقتصادية والإدارية + الاختبار البعدي",
    title_en="Applications in Economics & Management + Post-test",
    module="course.w01",
    order=3,
    prerequisites=["course.w01.core_concepts", "foundations.data.target"],
    objectives_ar=[
        "تحويل سؤال بحثي اقتصادي/إداري إلى مسألة تعلم آلي محددة (الملاحظة، الخصائص، الهدف ونوعه، نوع البيانات).",
        "اختيار عائلة البنية المناسبة لنوع البيانات.",
        "إثبات بالتجربة متى يتفوق خط الأساس البسيط على الشبكة، ومتى يحدث العكس.",
        "التمييز بين ما يقدمه النموذج (تنبؤ) وما لا يقدمه (سببية)، مع مثال محاكى.",
    ],
    terms=["target", "observation", "feature", "classification", "regression", "baseline", "time_series"],
    difficulty="beginner",
    summary_ar="من سؤال بحثي إلى مسألة تعلم عميق: الملاحظة والخصائص والهدف ونوع البيانات ← البنية. ابدأ بخط أساس؛ الشبكة تحتاج بيانات. التنبؤ ليس سببية.",
)

_TASK_STEPS = [
    ("Question", "**السؤال البحثي**: «هل سيتعثر هذا العميل في سداد قرضه؟» — سؤال يطرحه بنك قبل منح القرض. لم نتكلم عن شبكات بعد: نبدأ دائمًا من السؤال.", ("question", "—", "will default?")),
    ("Observation", "**الملاحظة** `observation`: ما الذي يمثله صف واحد؟ هنا **عميل واحد**. كل ما نعرفه عن العميل وقت الطلب يوضع في صفه.", ("row =", "?", "one customer")),
    ("Features", "**الخصائص** `features`: ما نعرفه **قبل** القرار: الدخل، العمر، عدد التأخرات السابقة، نسبة الدين، المدينة، الحالة الوظيفية. أي معلومة لا تُعرف إلا بعد التعثر ممنوعة (تسرب).", ("features", "?", "6 columns")),
    ("Target & type", "**الهدف** `target`: العمود `defaulted` (0/1). قيمتان فقط ⇒ **تصنيف ثنائي**. لو كان الهدف «المبلغ المفقود» لكان **انحدارًا**.", ("target", "?", "defaulted ∈ {0,1}")),
    ("Data type", "**نوع البيانات**: جدول منظم (أعمدة رقمية وفئوية). هذا يقترح `MLP` لا `CNN` (صور) ولا `LSTM` (تسلسل).", ("data", "?", "tabular")),
    ("Baseline → DL", "**خط الأساس أولًا**: انحدار لوجستي. ثم MLP. نقبل الشبكة فقط إذا تفوقت على بيانات اختبار محجوزة — وبفرق يبرر تعقيدها.", ("plan", "?", "logistic → MLP")),
]


def render() -> None:
    lesson_header(LESSON)

    # ------------------------------------------------------------------ question → task
    h2("من سؤال بحثي إلى مسألة تعلم عميق", "From research question to ML task")
    st.markdown("لكل سؤال بحثي أجب عن أربعة أسئلة بالترتيب: **ما الملاحظة؟ ما الخصائص؟ ما الهدف ونوعه؟ ما نوع البيانات؟** ثم فقط اختر البنية. شاهد الطريقة على مثال القروض:")
    frames = [Frame(loan_task_svg(i), caption(txt), action=name, values=[val], highlight=i) for i, (name, txt, val) in enumerate(_TASK_STEPS)]
    cur = animation_player("w01_task", frames, title_ar="«هل سيتعثر العميل؟» ← مسألة تعلم آلي",
                           stages=[s[0] for s in _TASK_STEPS], interval_ms=2600)
    df = loan_preview()
    if cur >= 1:
        cols = {1: None, 2: ["income", "age", "num_late_payments", "debt_ratio", "city", "employment"], 3: ["defaulted"]}.get(cur)
        st.caption("أول 6 صفوف (عملاء) من بيانات القروض التعليمية" + (" — الأعمدة المعنية بالخطوة الحالية مظللة." if cols else "."))
        st.dataframe(df.style.set_properties(subset=cols, **{"background-color": "#E0F3F1"}) if cols else df, hide_index=True)

    h3("نفس الطريقة على أسئلة أخرى", "The same recipe, more questions")
    compare_table(
        ["السؤال البحثي", "الملاحظة", "الهدف ونوعه", "نوع البيانات", "بنية مناسبة"],
        [
            ("هل سيتعثر هذا العميل؟", "عميل", "defaulted — تصنيف ثنائي", "جدولية", "MLP (بعد خط أساس لوجستي)"),
            ("ما سعر هذا العقار؟", "عقار", "price — انحدار", "جدولية (+ صور)", "MLP (+ CNN)"),
            ("ما تضخم الشهر القادم؟", "نافذة 24 شهرًا", "inflation(t+1) — انحدار زمني", "سلسلة زمنية", "LSTM / GRU"),
            ("هل هذه المراجعة سلبية؟", "مراجعة", "sentiment — تصنيف ثنائي", "نص", "RNN / Transformer"),
            ("أي قطاع تنتمي إليه الشركة من وصفها؟", "شركة", "sector — تصنيف متعدد الفئات", "نص", "RNN / Transformer"),
            ("كم الطلب غدًا على كل منتج؟", "منتج × يوم", "demand — انحدار زمني", "سلاسل زمنية متعددة", "GRU"),
            ("هل هذه الفاتورة مزورة؟", "صورة فاتورة", "fraud — تصنيف ثنائي", "صور", "CNN"),
            ("هل سيغادر هذا الموظف الشركة خلال سنة؟", "موظف", "attrition — تصنيف ثنائي", "جدولية", "MLP (بعد خط أساس)"),
            ("ما مستوى الفقر في هذه القرية؟", "صورة قمر صناعي لقرية", "poverty index — انحدار", "صور", "CNN"),
            ("هل يلمّح بيان البنك المركزي إلى رفع الفائدة؟", "بيان", "hawkish/dovish — تصنيف", "نص", "RNN / Transformer"),
        ],
        ["rtl", "rtl", "rtl", "rtl", "ltr"],
    )
    research_note("مثال بحثي منشور: Jean وزملاؤه (2016، مجلة *Science*) درّبوا CNN على صور الأقمار الصناعية للتنبؤ بمؤشرات الفقر في دول إفريقية تندر فيها المسوح الميدانية — "
                  "حالة نموذجية تكون فيها البيانات صورًا ولا يستطيع الباحث صنع الخصائص يدويًا.")
    compare_table(
        ["نوع البيانات", "البنية الطبيعية", "لماذا؟", "الأسبوع"],
        [("جدولية", "MLP", "لا ترتيب مكاني ولا زمني بين الأعمدة", "04–07"),
         ("صور", "CNN", "البكسلات المتجاورة مترابطة؛ نفس النمط قد يظهر في أي مكان", "08–09"),
         ("سلاسل زمنية / نص", "RNN / LSTM / GRU", "الترتيب مهم والذاكرة عبر الزمن ضرورية", "10–12")],
        ["rtl", "ltr", "rtl", "ltr"],
    )

    # ------------------------------------------------------------------ baseline vs DL
    h2("هل تحتاج شبكة عميقة أصلًا؟ تجربة حقيقية", "Do you even need a deep network? A real experiment")
    st.markdown("نفس المسألة (أسعار العقارات، 4 خصائص) بنموذجين: **انحدار خطي** (خط أساس) و**MLP** صغير بطبقتين مخفيتين (32 و16 وحدة). "
                "ندرّب كلًا منهما على عدد متزايد من العقارات، ثم نقيّمهما على **نفس 3000 عقار لم يرها أي منهما**. المقياس `R²` (1 = تنبؤ تام).")
    rows = size_experiment()
    fig = go_fig.Figure()
    fig.add_scatter(x=[r["n"] for r in rows], y=[r["linear"] for r in rows], mode="lines+markers", name="Linear regression (baseline)", line=dict(color="#2F6FB5", width=3))
    fig.add_scatter(x=[r["n"] for r in rows], y=[r["mlp"] for r in rows], mode="lines+markers", name="MLP (32, 16)", line=dict(color="#C8473A", width=3))
    fig.update_layout(xaxis=dict(title="training rows (houses)", type="log", tickvals=[r["n"] for r in rows]), yaxis=dict(title="test R²"),
                      height=380, margin=dict(l=10, r=10, t=60, b=10), legend=dict(orientation="h", x=0, y=1.18))
    st.plotly_chart(fig, width="stretch", key="w01_size_fig")
    compare_table(["عدد صفوف التدريب", "انحدار خطي R²", "MLP R²", "الفائز"],
                  [(str(r["n"]), f"{r['linear']:.3f}", f"{r['mlp']:.3f}", "خط الأساس" if r["linear"] >= r["mlp"] else "MLP") for r in rows],
                  ["ltr", "ltr", "ltr", "rtl"])
    first_win = next((r["n"] for r in rows if r["mlp"] > r["linear"]), None)
    interpretation_note(
        "مع بيانات قليلة يفوز الخط المستقيم: الشبكة لديها مئات المعلمات ولا تجد بيانات كافية لضبطها. "
        + (f"الشبكة تتفوق فقط ابتداءً من نحو {first_win} صف، لأن السعر يتضمن أثرًا **ضربيًا** للحي لا يلتقطه الخط المستقيم. " if first_win else "")
        + "الدرس: الشبكة لا تكون أفضل تلقائيًا؛ هي **أكثر مرونة**، والمرونة تحتاج بيانات."
    )
    warning_note("في التطبيقات الاقتصادية غالبًا **قلة البيانات** هي القيد: 150 صفًا لا تبرر شبكة عميقة. ابدأ بخط أساس (انحدار، أشجار) وقارن على بيانات محجوزة. "
                 "الشبكات تفوز عندما تكون البيانات كبيرة، أو غير مهيكلة (صور/نص)، أو تحوي تفاعلات معقدة.")

    # ------------------------------------------------------------------ prediction ≠ causation
    h2("حدود التفسير: التنبؤ ليس سببية — تجربة محاكاة", "Prediction is not causation — a simulation")
    st.markdown(
        "نحاكي بنكًا فيه متغير **غير مرصود**: «الضغط المالي» للعميل. الضغط المالي يسبب أمرين: **مكالمات أكثر** من قسم التحصيل، و**تعثرًا** أكثر. "
        "المكالمات نفسها **لا تسبب** التعثر إطلاقًا في هذه المحاكاة (نحن كتبنا الآلية ونعرفها)."
    )
    d = confounding_demo()
    c1, c2, c3 = st.columns(3)
    c1.metric("ارتباط المكالمات بالتعثر", f"{d['corr']:.2f}")
    c2.metric("قدرة التنبؤ (AUC على بيانات الاختبار)", f"{d['auc']:.2f}")
    c3.metric("معامل «المكالمات» في النموذج", f"{d['coef']:+.2f}")
    st.markdown("النموذج يتنبأ بالتعثر من المكالمات **جيدًا** (AUC فوق 0.5 بوضوح). الآن يقرر البنك: «لنوقف كل المكالمات فينخفض التعثر!» ماذا يحدث؟")
    fig2 = go_fig.Figure()
    fig2.add_bar(x=["before: calls on", "after: calls stopped"], y=[d["pred_before"] * 100, d["pred_after"] * 100], name="what the model predicts", marker_color="#C8473A")
    fig2.add_bar(x=["before: calls on", "after: calls stopped"], y=[d["rate_before"] * 100, d["rate_after"] * 100], name="what actually happens", marker_color="#2F6FB5")
    fig2.update_layout(barmode="group", yaxis=dict(title="default rate (%)"), height=360, margin=dict(l=10, r=10, t=60, b=10), legend=dict(orientation="h", x=0, y=1.18))
    st.plotly_chart(fig2, width="stretch", key="w01_causal_fig")
    st.caption("الأحمر: معدل التعثر الذي يتوقعه النموذج. الأزرق: معدل التعثر الفعلي في المحاكاة.")
    research_note(
        f"النموذج «يتوقع» أن ينخفض التعثر من {d['pred_before'] * 100:.1f}% إلى {d['pred_after'] * 100:.1f}%، لكن المعدل الفعلي يبقى نحو {d['rate_after'] * 100:.1f}% "
        "لأن المكالمات كانت **علامة** على الضغط المالي لا **سببًا** للتعثر. "
        "**تنبؤ ≠ سببية**: للاستدلال السببي تحتاج تصميمًا تجريبيًا أو طرق الاقتصاد القياسي السببي (متغيرات أداتية، فروق في الفروق…)، لا شبكة أدق. "
        "سنميز في المقرر بين: تنبؤ، تفسير إحصائي، تفسير اقتصادي، وادعاء سببي."
    )
    common_mistake("كتابة «المتغير X هو أهم محدد للتعثر» استنادًا إلى أهمية خاصية في نموذج تنبؤي. الأهمية التنبؤية تعني «مفيد للتنبؤ»، لا «يسبب».")

    # ------------------------------------------------------------------ post-test
    h2("الاختبار البعدي", "Post-test")
    quiz(
        "w01.posttest",
        [
            Q("التعلم العميق هو…", ["مرادف للذكاء الاصطناعي", "فرع من التعلم الآلي يستخدم شبكات متعددة الطبقات", "أي برنامج يستخدم بيانات"], 1,
              "AI ⊃ ML ⊃ DL: DL حالة خاصة من ML دالتها شبكة متعددة الطبقات."),
            Q("أثناء الاستدلال، المعلمات…", ["تتغير", "مجمّدة", "تُحذف"], 1, "الاستدلال تمرير أمامي فقط؛ التحديث يحدث في التدريب وحده."),
            Q("«ما تضخم الشهر القادم؟» — الملاحظة المناسبة هي…", ["شهر واحد", "نافذة من أشهر متتالية", "كل السلسلة"], 1,
              "النافذة الزمنية هي الملاحظة في مسائل التسلسل."),
            Q("«هل يلمّح بيان البنك المركزي إلى رفع الفائدة؟» — نوع المسألة والبيانات:", ["انحدار على جدول", "تصنيف على نص", "تصنيف على صور"], 1,
              "الهدف فئة (يرفع/لا يرفع) والمدخل نص."),
            Q("جدول 150 صفًا عن شركات وهدف عددي. الخطوة الأولى الصحيحة؟", ["شبكة بعشر طبقات", "خط أساس بسيط ثم مقارنة", "LSTM"], 1,
              "رأينا بالتجربة أن الخط المستقيم يتفوق على MLP عند 150 صفًا."),
            Q("في تجربة أسعار العقارات، لماذا تفوقت MLP عند 2000 صف فقط؟", ["لأن الشبكات دائمًا أفضل", "لأن مرونتها تحتاج بيانات كافية لتتعلم أثر الحي الضربي", "بسبب الصدفة"], 1,
              "المرونة بلا بيانات = تباين كبير؛ مع البيانات = التقاط أنماط لا يراها الخط."),
            Q("الخسارة انفجرت إلى inf أثناء التدريب. أول ما تجربه؟", ["زيادة الحقب", "تقليل معدل التعلم η", "إضافة طبقات"], 1, "η كبير يجعل الخطوات تتجاوز القاع."),
            Q("نموذج دقيق جدًا في التنبؤ يعني…", ["أنه اكتشف السبب", "أنه يتنبأ جيدًا فقط", "أنه لا يحتاج تقييمًا"], 1,
              "محاكاة المكالمات: تنبؤ جيد، ومع ذلك التدخل لم يغيّر التعثر."),
        ],
        title_ar="الاختبار البعدي — الأسبوع 01",
    )
    takeaway("حوّل السؤال إلى: ملاحظة، خصائص، هدف ونوعه، نوع البيانات ← بنية. ابدأ بخط أساس؛ الشبكة تحتاج بيانات لتتفوق. وتذكر: التنبؤ ليس سببية.")
    lesson_footer(LESSON, [
        "أربعة أسئلة تحوّل أي سؤال بحثي إلى مسألة تعلم آلي.",
        "نوع البيانات يقترح عائلة البنية: جدولية MLP، صور CNN، تسلسل RNN/LSTM/GRU.",
        "بالتجربة: خط الأساس يفوز بالبيانات القليلة، والشبكة تحتاج بيانات أكثر.",
        "تنبؤ ≠ سببية: متغير مُربك غير مرصود قد يصنع تنبؤًا جيدًا بلا أي أثر سببي.",
    ])
