def render() -> None:
    lesson_header(LESSON)
    why("رمز معلن قبل التسليم يجعل التقييم عادلًا ويحوّله إلى دليل عمل: كل بند هو مرحلة من الأسبوع 14 بمستويات موصوفة. قيّم نفسك أدناه قبل أن يقيّمك غيرك.")
    h2("الرمز النهائي", "The final rubric")
    rows = [(name, str(w), lv[0], lv[1], lv[2], lv[3]) for name, w, lv in RUBRIC]
    table(["البند", "الوزن", "0", "1", "2", "3"], rows, ["rtl", "num", "rtl", "rtl", "rtl", "rtl"])
    st.caption("الدرجة = Σ (المستوى/3 × الوزن) من 100. المستوى 3 هو ما وصفه الأسبوع 14 كاملًا.")
    h2("التقييم الذاتي", "Self-assessment")
    st.session_state.setdefault("w15_self", {})
    total = 0.0; weak = []
    for name, w, lv in RUBRIC:
        c1, c2 = st.columns([2, 3], vertical_alignment="center")
        with c1:
            st.markdown(f"**{name}** ({w})")
        with c2:
            level = st.select_slider("المستوى", options=[0, 1, 2, 3], value=st.session_state["w15_self"].get(name, 0), key=f"w15_lv_{name}", label_visibility="collapsed", format_func=lambda v, lv=lv: f"{v} — {lv[v][:42]}{'…' if len(lv[v]) > 42 else ''}")
        st.session_state["w15_self"][name] = level
        total += level / 3 * w
        if level <= 1:
            weak.append((name, w, lv[level + 1] if level < 3 else ""))
    st.progress(total / 100, text=f"الدرجة التقديرية: {total:.0f} / 100")
    if weak:
        st.markdown("**البنود التي تستحق العمل أولًا (مرتبة بالوزن):**")
        for name, w, nxt in sorted(weak, key=lambda t: -t[1]):
            st.markdown(f"- **{name}** ({w} نقطة): للمستوى التالي — {nxt}")
    else:
        st.success("كل البنود عند المستوى 2 أو 3. راجع الأسبوع 14 للوصول إلى 3 حيث أمكن.", icon="✅")
    intuition("الأوزان تقول ما يهم: تجنّب التسريب (10) + التقسيم وخط الأساس (12) + التقييم (14) = 36% من الدرجة قبل أي كلمة عن الدقة. الاستنساخ وجودة الكود (14) يفوقان النموذج (8). هذا هو المقرر في رقم واحد.")
    h2("جودة الاستنساخ والعرض", "Reproducibility & presentation quality")
    compare_table(["البند", "الحد الأدنى", "الممتاز"],
                  [("الدفتر", "يعمل من الأول بعد Restart and run all", "+ خلايا مرقّمة بالمراحل، مخرجات محفوظة، لا خلايا ميتة"), ("البيانات", "مسار واضح أو رابط", "+ عينة صغيرة مرفقة تسمح بتشغيل سريع"), ("البذرة والنسخ", "مطبوعة في الخلية الأولى", "+ run.json بالتقسيم والمقاييس والإحصاءات"),
                   ("الزمن والجهاز", "مذكوران", "+ نقاط حفظ في Drive وإرشاد الاستئناف"), ("العرض", "10 شرائح بالترتيب", "+ الأرقام بوحدة الهدف مقابل خط الأساس في كل مكان"), ("المناقشة", "أجوبة على الأسئلة العشرة", "+ نقاط الضعف معلنة قبل السؤال")],
                  ["rtl", "rtl", "rtl"])
    practical_note("قبل التسليم: (1) Restart and run all؛ (2) قارن أرقام الدفتر بأرقام الشرائح؛ (3) تأكد أن خط الأساس في الشريحة 4 وفي جدول التقييم؛ (4) اقرأ الرمز مرة أخيرة.")
    with st.container(horizontal=True):
        st.button("الأسبوع 14 — القالب", icon=":material/description:", on_click=goto, args=("course.w14.notebook_template",), key="w15_go_tpl")
        st.button("الوحدة 23 — حالة الجاهزية", icon=":material/verified:", on_click=goto, args=("foundations.ready.ready_status",), key="w15_go_ready")
